use std::ops::Range;

// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
///
// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
#[derive(Clone, PartialEq)]
pub enum TokenType {
    TAG_BEGIN,
    TAG_BEGIN_CLOSE,
    TAG_BEGIN_INSTRUCTION,
    TAG_END,
    TAG_END_CLOSE,
    TAG_END_INSTRUCTION,
    /// Наименование тега
    /// Tag name
    TAG_NAME,

    /// Токен закрытия тега.
    /// Tag closing token.
    //CLOSE,

    /// Наименование атрибута
    /// Attribute name
    ATTRIBUTE_NAME,
    /// Значение атрибута
    /// Attribute value
    ATTRIBUTE_VALUE,
    /// Токен завершения работы парсера.
    /// Parser completion token.
    END,
}

// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
/// # example
///
/// `<tag>`
///
/// Token:
/// - `r#type` = `TAG_NAME`
/// - `data` = `tag`
///
// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
pub struct Token {
    /// Тип токена
    /// Token type
    pub(crate) r#type : TokenType,
    /// Данные токена
    /// Token data
    pub(crate) data_rng : Range<usize>,
}

// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
/// Публичные ассоциированные функции.
/// Public associated functions.
// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
impl Token {
    // ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    ///
    // ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    pub fn s_create(r#type: TokenType, data_rng: Range<usize>) -> Self {
        Self {
            r#type,
            data_rng: data_rng,
        }
    }

    // ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    ///
    // ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    pub fn s_createEmpty() -> Self {
        Self {
            r#type: TokenType::TAG_END,
            data_rng: (0 .. 0),
        }
    }
}

// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
/// Публичные методы.
/// Public methods.
// ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
impl Token {
    // ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    ///
    // ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    pub fn asType(&self) -> TokenType {
        self.r#type.clone()
    }

    // ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    ///
    // ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    pub fn asRange(&self) -> Range<usize> {
        self.data_rng.clone()
    }

    // ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    //
    // ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    pub unsafe fn asStr<'a>(&self, data: &'a [u8]) -> &'a str {
        let str_ = std::str::from_utf8_unchecked(&data[self.data_rng.start..self.data_rng.end]);
        str_
    }
}

